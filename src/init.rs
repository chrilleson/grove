//! `grove init`: config, tmux conf and Claude Code hooks. Never rewrites the
//! user's own files; the only edit to someone else's file is grove's own
//! hook entries in Claude Code's settings, recognised by their command.

use crate::config::Config;
use anyhow::{Context, Result};
use serde_json::{Value, json};
use std::io::{BufRead, Write};
use std::path::PathBuf;

/// Hook events grove listens to. Team events are only logged for now (spec).
pub const HOOK_EVENTS: &[&str] = &[
    "UserPromptSubmit",
    "PreToolUse",
    "Notification",
    "PermissionRequest",
    "Stop",
    "SessionEnd",
    "SubagentStart",
    "SubagentStop",
    "TeammateIdle",
    "TaskCreated",
    "TaskCompleted",
];

/// Events whose hook entries take a tool matcher.
const MATCHER_EVENTS: &[&str] = &["PreToolUse", "PermissionRequest"];

pub fn tmux_conf(config: &Config, exe: &str) -> String {
    let k = &config.keys;
    let mut c = String::new();
    let mut line = |s: String| {
        c.push_str(&s);
        c.push('\n');
    };
    line("# Generated by `grove init`. Re-run it to regenerate; change keys in config.toml.".into());
    line("# grove binds only M-… keys in the root table. Make ⌥ send Alt in your terminal (see `grove doctor`).".into());
    line(String::new());
    let popup = format!("display-popup -E -b rounded -S fg={}", crate::theme::LINE_HI);
    line(format!("bind-key -n {} run-shell -b '{exe} next'", k.next));
    line(format!(
        "bind-key -n {} {popup} -w 90% -h 80% '{exe} dash'",
        k.dashboard
    ));
    line(format!("bind-key -n {} switch-client -l", k.last));
    if k.numbers {
        for n in 1..=9 {
            line(format!("bind-key -n M-{n} run-shell -b '{exe} go {n}'"));
        }
    }
    line(format!(
        "bind-key -n {} run-shell -b '{exe} open lazygit'",
        k.lazygit
    ));
    line(format!(
        "bind-key -n {} run-shell -b '{exe} open editor'",
        k.editor
    ));
    line(format!("bind-key -n {} run-shell -b '{exe} open code'", k.vscode));
    line(format!("bind-key -n {} {popup} -w 90% -h 70% '{exe} new'", k.new));
    line(format!("bind-key -n {} switch-client -T grove", k.leader));
    line(format!(
        "bind-key -T grove x confirm-before -p 'remove task #S? (y/n)' \"run-shell '{exe} rm'\""
    ));
    line(String::new());
    line("# Once per server, so re-sourcing doesn't stack the counter or the hook.".into());
    line("if-shell -F '#{!=:#{@grove-loaded},1}' {".into());
    line(format!("  set-option -ga status-right ' #({exe} status --tmux)'"));
    line(format!(
        "  set-hook -ga client-session-changed \"run-shell -b '{exe} visit #{{client_session}}'\""
    ));
    line("  set-option -g @grove-loaded 1".into());
    line("}".into());
    line("set-option -g status-interval 5".into());
    c
}

pub(crate) fn is_grove_entry(entry: &Value) -> bool {
    entry["hooks"].as_array().is_some_and(|hs| {
        hs.iter().any(|h| {
            let cmd = h["command"].as_str().unwrap_or("");
            let mut parts = cmd.split_whitespace();
            let bin = parts.next().unwrap_or("").trim_matches(['\'', '"']);
            bin.rsplit('/').next() == Some("grove") && parts.next() == Some("hook")
        })
    })
}

/// Add grove's hook entries, replacing any earlier grove entries and leaving
/// everything else alone.
pub fn merge_claude_hooks(mut settings: Value, exe: &str) -> Value {
    if !settings.is_object() {
        settings = json!({});
    }
    if !settings["hooks"].is_object() {
        settings["hooks"] = json!({});
    }
    let hooks = settings["hooks"].as_object_mut().unwrap();
    for event in HOOK_EVENTS {
        let list = hooks.entry(event.to_string()).or_insert_with(|| json!([]));
        if !list.is_array() {
            *list = json!([]);
        }
        let arr = list.as_array_mut().unwrap();
        arr.retain(|e| !is_grove_entry(e));
        let mut entry = json!({ "hooks": [{ "type": "command", "command": format!("{exe} hook {event}") }] });
        if MATCHER_EVENTS.contains(event) {
            entry["matcher"] = json!("*");
        }
        arr.push(entry);
    }
    settings
}

pub fn claude_settings_path() -> PathBuf {
    match std::env::var_os("CLAUDE_CONFIG_DIR") {
        Some(d) if !d.is_empty() => PathBuf::from(d).join("settings.json"),
        _ => PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join(".claude/settings.json"),
    }
}

fn default_config_toml(roots: &[String]) -> String {
    let roots = roots
        .iter()
        .map(|r| format!("{r:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "# grove config. See docs/spec.md for every key.\n\
         roots = [{roots}]\n\
         # worktree_root = \"~/worktrees\"\n\
         default_team = false\n\
         agent_command = \"claude\"\n\
         editor = \"nvim\"\n\
         notify = true\n\
         \n\
         [attention]\n\
         blink_after = \"2m\"\n\
         renotify_after = \"10m\"\n\
         \n\
         [ports]\n\
         start = 20000\n\
         block = 10\n"
    )
}

fn ask_roots() -> Result<Vec<String>> {
    eprint!("Directories that hold your repos, comma-separated (e.g. ~/dev/personal, ~/dev/work): ");
    std::io::stderr().flush()?;
    let mut s = String::new();
    std::io::stdin().lock().read_line(&mut s)?;
    Ok(s.split(',')
        .map(str::trim)
        .filter(|r| !r.is_empty())
        .map(String::from)
        .collect())
}

pub fn run(dry_run: bool, roots: Vec<String>) -> Result<()> {
    let exe = std::env::current_exe()?.to_string_lossy().into_owned();
    let mut changes: Vec<(PathBuf, String, &str)> = vec![];

    let config_path = Config::path();
    let config = if config_path.exists() {
        println!("keep   {} (exists)", config_path.display());
        Config::load()?
    } else {
        let roots = if roots.is_empty() && !dry_run {
            ask_roots()?
        } else {
            roots
        };
        let text = default_config_toml(&roots);
        let cfg: Config = toml::from_str(&text)?;
        changes.push((config_path, text, "write"));
        cfg
    };

    let tmux_path = crate::paths::config_dir().join("grove.tmux.conf");
    changes.push((tmux_path.clone(), tmux_conf(&config, &exe), "write"));

    let settings_path = claude_settings_path();
    let current: Value = match std::fs::read_to_string(&settings_path) {
        Ok(s) => serde_json::from_str(&s).with_context(|| format!("parsing {}", settings_path.display()))?,
        Err(_) => json!({}),
    };
    let merged = merge_claude_hooks(current.clone(), &exe);
    if merged != current {
        changes.push((
            settings_path,
            serde_json::to_string_pretty(&merged)? + "\n",
            "update hooks in",
        ));
    }

    for (path, text, verb) in &changes {
        if dry_run {
            println!("--- would {verb} {} ---\n{text}", path.display());
        } else {
            std::fs::create_dir_all(path.parent().unwrap())?;
            std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
            println!("{verb:<6} {}", path.display());
        }
    }
    println!("\nAdd this line at the end of your tmux.conf, then reload tmux:");
    println!("  source-file {}", tmux_path.display());
    if cfg!(target_os = "macos") {
        println!("\nOn macOS, make ⌥ send Alt (Ghostty: `macos-option-as-alt = true`).");
    }
    Ok(())
}
